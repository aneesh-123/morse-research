/**
 * Reproducible seeded randomness.
 *
 * Algorithm (documented in docs/PROTOCOL.md so schedules can be rebuilt in other languages):
 *  - The seed string is hashed with cyrb128 into four 32-bit words.
 *  - Those words seed an sfc32 generator, which returns floats in [0, 1).
 *  - Shuffles use the Fisher–Yates algorithm drawing j = floor(rng() * (i + 1)) for i from n-1 down to 1.
 *
 * Every schedule is also stored verbatim in the database, so reproduction does not depend on this
 * code staying unchanged; the algorithm is versioned with the protocol (randomization.algorithm).
 */

export const RNG_ALGORITHM = 'cyrb128-sfc32-fisher-yates-v1';

function cyrb128(str: string): [number, number, number, number] {
  let h1 = 1779033703, h2 = 3144134277, h3 = 1013904242, h4 = 2773480762;
  for (let i = 0; i < str.length; i++) {
    const k = str.charCodeAt(i);
    h1 = h2 ^ Math.imul(h1 ^ k, 597399067);
    h2 = h3 ^ Math.imul(h2 ^ k, 2869860233);
    h3 = h4 ^ Math.imul(h3 ^ k, 951274213);
    h4 = h1 ^ Math.imul(h4 ^ k, 2716044179);
  }
  h1 = Math.imul(h3 ^ (h1 >>> 18), 597399067);
  h2 = Math.imul(h4 ^ (h2 >>> 22), 2869860233);
  h3 = Math.imul(h1 ^ (h3 >>> 17), 951274213);
  h4 = Math.imul(h2 ^ (h4 >>> 19), 2716044179);
  h1 ^= h2 ^ h3 ^ h4; h2 ^= h1; h3 ^= h1; h4 ^= h1;
  return [h1 >>> 0, h2 >>> 0, h3 >>> 0, h4 >>> 0];
}

export type Rng = () => number;

export function createRng(seed: string): Rng {
  let [a, b, c, d] = cyrb128(seed);
  return () => {
    a >>>= 0; b >>>= 0; c >>>= 0; d >>>= 0;
    let t = (a + b) | 0;
    a = b ^ (b >>> 9);
    b = (c + (c << 3)) | 0;
    c = (c << 21) | (c >>> 11);
    d = (d + 1) | 0;
    t = (t + d) | 0;
    c = (c + t) | 0;
    return (t >>> 0) / 4294967296;
  };
}

export function shuffle<T>(items: readonly T[], rng: Rng): T[] {
  const a = items.slice();
  for (let i = a.length - 1; i > 0; i--) {
    const j = Math.floor(rng() * (i + 1));
    [a[i], a[j]] = [a[j] as T, a[i] as T];
  }
  return a;
}
